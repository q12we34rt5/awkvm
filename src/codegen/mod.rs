pub fn emit(
    module: &Module,
    inline_asm: &[(String, String)],
    linked: &[String],
) -> Result<String> {
    let mut out = String::new();
    let _ = writeln!(out, "# Generated by awkvm from {}", module.name);
    let _ = writeln!(out, "# Requires gawk (uses and/or/xor/lshift/rshift built-ins)");
    let _ = writeln!(out);

    let _ = writeln!(out, "{RUNTIME}");

    // Linked awk: any `--link <file>` arg's content is emitted verbatim
    // right after the runtime so it can use _alloc / _cstr / _str_to_mem
    // / etc. Every `function fn_<name>(...)` defined in here becomes
    // callable from C-side `extern <T> <name>(...)` — matched up via the
    // declare-only-stub suppression below.
    let mut linked_fn_c_names: HashSet<String> = HashSet::new();
    for awk in linked {
        out.push_str(awk);
        if !awk.ends_with('\n') {
            out.push('\n');
        }
        linked_fn_c_names.extend(extract_link_fn_names(awk));
    }
    let _ = writeln!(out);

    let fn_ids = build_fn_ids(module);
    let mut cx = LayoutCx::new(&module.types, inline_asm);

    globals::emit_globals_init(&mut out, module, &fn_ids, &mut cx)?;

    if let Some(main_fn) = module.functions.iter().find(|f| f.name == "main") {
        match main_fn.parameters.len() {
            0 => {
                let _ = writeln!(out, "BEGIN {{ exit fn_main() }}");
            }
            2 => {
                // int main(int argc, char** argv)
                let _ = writeln!(out, "BEGIN {{ exit fn_main(ARGC, _build_argv()) }}");
            }
            3 => {
                // int main(int argc, char** argv, char** envp) — we don't
                // model env, so pass NULL.
                let _ = writeln!(out, "BEGIN {{ exit fn_main(ARGC, _build_argv(), 0) }}");
            }
            n => bail!("main has {n} parameters; only 0, 2, or 3 are supported"),
        }
        let _ = writeln!(out);
    }

    for func in &module.functions {
        func::emit_function(&mut out, func, &mut cx)?;
    }

    // libc / Itanium ABI helpers. Skip any that the user has provided their
    // own definition of (custom operator new, malloc override, etc.) — their
    // body has already been emitted above as fn_<name>.
    let user_defined: HashSet<&str> = module
        .functions
        .iter()
        .filter(|f| !f.basic_blocks.is_empty())
        .map(|f| f.name.as_str())
        .collect();
    let helpers = parse_libc_helpers(LIBC);
    let helper_names: HashSet<&str> = helpers.iter().map(|(n, _)| n.as_str()).collect();
    let probe_names: HashSet<&str> = PROBE_MAP.iter().map(|(m, _)| *m).collect();

    // Toolchain coupling check: warn loudly when the user's IR
    // references a libc++ symbol whose tag-stripped form matches a
    // probe entry but whose full mangled name doesn't. That's almost
    // always an Apple-Clang-vs-Homebrew-Clang style mismatch — both
    // libc++ versions name the same function, but tag it with their
    // own ABI version (e.g. `B8ne190102` vs `B8ne190107`), so the
    // recognized-call path silently degrades to a no-op stub.
    let probe_stripped: HashSet<String> =
        PROBE_MAP.iter().map(|(m, _)| strip_abi_tags(m)).collect();
    // Walk both functions and func_declarations: at -O1 the templated
    // libc++ helpers stay external (declarations only) and our probes
    // capture them; at -O0 clang fully inlines them into user.ll as
    // user-defined function bodies. Either way they show up in the IR
    // and can mismatch on ABI tag.
    let mismatched: HashSet<String> = module
        .functions
        .iter()
        .map(|f| f.name.as_str())
        .chain(module.func_declarations.iter().map(|d| d.name.as_str()))
        .filter(|name| !probe_names.contains(name))
        .filter_map(|name| {
            let stripped = strip_abi_tags(name);
            if probe_stripped.contains(&stripped) {
                Some(format!("{name}\n  Tag-stripped form: {stripped}"))
            } else {
                None
            }
        })
        .collect();
    for entry in &mismatched {
        eprintln!(
            "awkvm: warning: `{entry}`\n  This looks like a probe-targeted \
             libc++ symbol whose ABI tag doesn't match PROBE_MAP. Calls \
             route to a no-op stub (or to a user-body wrapper that itself \
             calls a no-op stub), so output silently degrades. Hint: did \
             your .ll come from a different clang than $LLVM_SYS_191_PREFIX? \
             See LIMITATIONS.md \"Toolchain coupling\"."
        );
    }

    // Stubs for `declare`-only functions: any libc / Itanium symbol the
    // program references but doesn't define. Skip those covered by helpers
    // (which are about to be emitted as fn_<name>) or by the probe map
    // (whose call sites have been rewritten in-line, so fn_<name> is dead
    // code we'd rather not emit at all).
    for decl in &module.func_declarations {
        if helper_names.contains(decl.name.as_str())
            || probe_names.contains(decl.name.as_str())
            || linked_fn_c_names.contains(decl.name.as_str())
        {
            continue;
        }
        let params: Vec<String> = decl
            .parameters
            .iter()
            .map(|p| name_to_var(&p.name))
            .collect();
        let _ = writeln!(
            &mut out,
            "function {}({}) {{}}",
            func_to_var(&decl.name),
            params.join(", ")
        );
    }
    let _ = writeln!(&mut out);

    for (name, body) in &helpers {
        if user_defined.contains(name.as_str()) {
            continue;
        }
        out.push_str(body);
        out.push('\n');
    }
    let _ = writeln!(&mut out);

    globals::emit_icall_dispatcher(&mut out, module, &fn_ids)?;
    Ok(out)
}

// Walks libc.awk and returns each helper as (c_name, awk_function_text).
// Each helper is one `function fn_<c_name>(...) { ... }` definition; lines
// preceding it (comments, blanks) are dropped — they document the source
// file but aren't useful in the generated script. Brace balance is tracked
// so a one-liner block like `function fn_atol(s) { return _atoi(s) }` and
// a multi-line body both work.
fn parse_libc_helpers(text: &str) -> Vec<(String, String)> {
    fn brace_delta(s: &str) -> i32 {
        s.matches('{').count() as i32 - s.matches('}').count() as i32
    }
    let mut out: Vec<(String, String)> = Vec::new();
    let mut iter = text.lines().peekable();
    while let Some(line) = iter.next() {
        let trimmed = line.trim_start();
        let Some(after) = trimmed.strip_prefix("function fn_") else {
            continue;
        };
        let end = after
            .find(|c: char| c == '(' || c.is_whitespace())
            .expect("malformed libc.awk: function header without '('");
        let name = after[..end].to_string();
        let mut body = String::from(line);
        let mut depth = brace_delta(line);
        while depth > 0 {
            let next = iter
                .next()
                .expect("malformed libc.awk: unbalanced braces in helper body");
            body.push('\n');
            body.push_str(next);
            depth += brace_delta(next);
        }
        body.push('\n');
        out.push((name, body));
    }
    out
}

// Extract the C-level names of every `function fn_<name>(...)`
// definition in linked awk text. Used by emit() to suppress
// declare-only stubs whose name matches a linked definition (without
// suppression awk would see two `fn_<name>` definitions and refuse
// to parse). The linked function must be on its own line starting
// with optional whitespace + `function fn_`; closing-brace placement
// and body content don't matter to this scanner.
fn extract_link_fn_names(text: &str) -> HashSet<String> {
    let mut out = HashSet::new();
    for line in text.lines() {
        let trimmed = line.trim_start();
        let Some(after) = trimmed.strip_prefix("function fn_") else {
            continue;
        };
        let end = after
            .find(|c: char| !(c.is_alphanumeric() || c == '_'))
            .unwrap_or(after.len());
        if end == 0 {
            continue;
        }
        let rest = after[end..].trim_start();
        if !rest.starts_with('(') {
            continue;
        }
        out.insert(after[..end].to_string());
    }
    out
}

// Strip Itanium ABI tags (`B<length><tag-chars>`) from a mangled name.
// Used to detect toolchain mismatches: two libc++ versions naming the
// same templated helper differ only in the tag content (e.g.
// `B8ne190102` vs `B8ne190107`), so both reduce to the same canonical
// form after stripping.
fn strip_abi_tags(s: &str) -> String {
    let bytes = s.as_bytes();
    let mut out = String::with_capacity(s.len());
    let mut i = 0;
    while i < bytes.len() {
        // ABI-tag prefix: `B` followed by an ASCII digit sequence
        // giving the tag length, then that many tag-chars.
        if bytes[i] == b'B' && i + 1 < bytes.len() && bytes[i + 1].is_ascii_digit() {
            let mut j = i + 1;
            let mut len = 0usize;
            while j < bytes.len() && bytes[j].is_ascii_digit() {
                len = len * 10 + (bytes[j] - b'0') as usize;
                j += 1;
            }
            if j + len <= bytes.len() {
                i = j + len;
                continue;
            }
        }
        out.push(bytes[i] as char);
        i += 1;
    }
    out
}

// Assign sequential ids (starting at 1; 0 reserved for null) to every defined
// function. Declared-only functions are skipped — they have no awk body.
fn build_fn_ids(module: &Module) -> HashMap<String, i64> {
    module
        .functions
        .iter()
        .filter(|f| !f.basic_blocks.is_empty())
        .enumerate()
        .map(|(i, f)| (f.name.clone(), (i + 1) as i64))
        .collect()
}
